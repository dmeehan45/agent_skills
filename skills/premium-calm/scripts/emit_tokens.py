# ---------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description="Emit premium-calm tokens for every platform.")
    ap.add_argument("spec", help="token spec JSON")
    ap.add_argument("--out", default="tokens", help="output directory (default: tokens)")
    ap.add_argument("--formats", default=",".join(ALL_FORMATS), help=f"comma-separated: {', '.join(ALL_FORMATS)}")
    ap.add_argument("--preview", action="store_true", help="also write preview.html")
    ap.add_argument("--allow-failing", action="store_true",
                    help="emit even when contrast pairs fail (default: refuse)")
    args = ap.parse_args()

    spec = json.loads(Path(args.spec).read_text())
    formats = [f.strip() for f in args.formats.split(",") if f.strip()]
    unknown = [f for f in formats if f not in ALL_FORMATS]
    if unknown:
        ap.error(f"unknown format(s): {', '.join(unknown)}")

    failures = [r for r in check_spec(spec) if not r["pass"]]
    if failures and not args.allow_failing:
        print(f"Refusing to emit: {len(failures)} contrast pair(s) fail.", file=sys.stderr)
        for r in failures:
            detail = r["error"] or f"{r['ratio']}:1 < {r['min']}"
            print(f"  {r['mode']}: {r['fg']} on {r['bg']} — {detail}", file=sys.stderr)
        print("\nFix the tokens and re-run, or pass --allow-failing to emit anyway.", file=sys.stderr)
        return 1

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    written: list[str] = []

    def write(rel: str, content: str) -> None:
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        written.append(rel)

    if "css" in formats:
        write("tokens.css", emit_css(spec))
    if "tailwind3" in formats:
        write("tailwind.theme.js", emit_tailwind3(spec))
    if "tailwind4" in formats:
        write("tailwind.theme.css", emit_tailwind4(spec))
    if "json" in formats:
        write("tokens.json", emit_json(spec))
    if "swift" in formats:
        write("Tokens.swift", emit_swift(spec))
    if "android" in formats:
        for rel, content in emit_android(spec).items():
            write(rel, content)
    if args.preview:
        write("preview.html", emit_preview(spec))

    print(f"Wrote {len(written)} file(s) to {out}/")
    for rel in written:
        print(f"  {rel}")
    if failures:
        print(f"\nEmitted with {len(failures)} failing contrast pair(s) — do not ship without fixing them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
